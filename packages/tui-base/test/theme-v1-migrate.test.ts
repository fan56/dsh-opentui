import { describe, expect, test } from "bun:test"
import { parseTheme } from "../src/theme/index"
import { DEFAULT_THEMES } from "../src/theme/v1"
import { resolveThemeDocument } from "../src/vendor/theme/src/tui/resolve"
import { resolveV1 } from "../src/vendor/theme/src/tui/v1-migrate"
import type { RGBA } from "@opentui/core"

/**
 * Pins for fix/theme-legacy (v1 migration fidelity + lucent-orng light mode):
 *
 * 1. Accent fidelity — migrateV1 used to alias accent/primary onto an inferred chromatic
 *    family anchored at step 200, so the canonical step 500 that consumers read (powerline
 *    brand, prompt spinner, status bar) was a dark interpolation of the original hex
 *    (tokyonight #ff966c → #9c5133). accent/interactive are now their own scales anchored
 *    at the original token color, so resolved accent[500]/interactive[500] must equal the
 *    original V1 hex for every bundled theme and mode. Other steps stay interpolated.
 * 2. lucent-orng — its background/panel/element colors are "transparent"; the neutral scale
 *    used to anchor steps 800/700/600 on #00000000, rendering light-mode text (#1a1a1a) on
 *    effectively black. Transparent surface anchors are now solidified to the theme's first
 *    visible surface, made opaque, and the light mode must clear WCAG AA (4.5:1).
 */

function modesOf(document: unknown): ("light" | "dark")[] {
	return (["light", "dark"] as const).filter((mode) => mode in (document as Record<string, unknown>))
}

function hex(color: RGBA) {
	const [r, g, b] = color.toInts()
	const byte = (value: number) => value.toString(16).padStart(2, "0")
	return `#${byte(r)}${byte(g)}${byte(b)}`
}

/** WCAG 2.x contrast ratio between two opaque colors. */
function contrast(first: RGBA, second: RGBA) {
	const luminance = (color: RGBA) => {
		const channel = (value: number) => {
			const scaled = value / 255
			return scaled <= 0.04045 ? scaled / 12.92 : ((scaled + 0.055) / 1.055) ** 2.4
		}
		const [r, g, b] = color.toInts()
		return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)
	}
	const [high, low] = [luminance(first), luminance(second)].sort((a, b) => b - a)
	return (high + 0.05) / (low + 0.05)
}

describe("v1 migration keeps the original accent hex (fix/theme-legacy)", () => {
	test("accent[500] and interactive[500] equal the original V1 hex for every bundled theme/mode", () => {
		const misses: string[] = []
		for (const [name, source] of Object.entries(DEFAULT_THEMES)) {
			const document = parseTheme(source as unknown as Record<string, unknown>, name)
			for (const mode of modesOf(document)) {
				const original = resolveV1(source as never, mode)
				const resolved = resolveThemeDocument(document, mode)
				if (!resolved.hue.accent[500].equals(original.accent)) {
					misses.push(`${name}/${mode} accent ${hex(resolved.hue.accent[500])} != ${hex(original.accent)}`)
				}
				if (!resolved.hue.interactive[500].equals(original.primary)) {
					misses.push(`${name}/${mode} primary ${hex(resolved.hue.interactive[500])} != ${hex(original.primary)}`)
				}
			}
		}
		expect(misses).toEqual([])
	})

	test("sampled themes pin their exact brand hexes at step 500", () => {
		// Pre-fix these resolved to dark family interpolations (#9c5133 for tokyonight dark).
		const samples: [string, "light" | "dark", string, string][] = [
			["tokyonight", "dark", "#ff966c", "#82aaff"],
			["tokyonight", "light", "#b15c00", "#2e7de9"],
			["gruvbox", "dark", "#8ec07c", "#83a598"],
			["dracula", "dark", "#8be9fd", "#bd93f9"],
			["aura", "dark", "#a277ff", "#a277ff"],
		]
		for (const [name, mode, accent, primary] of samples) {
			const resolved = resolveThemeDocument(parseTheme(DEFAULT_THEMES[name] as unknown as Record<string, unknown>, name), mode)
			expect(hex(resolved.hue.accent[500])).toBe(accent)
			expect(hex(resolved.hue.interactive[500])).toBe(primary)
		}
	})

	test("non-anchor steps stay generated by the scale (interpolation, not echo)", () => {
		const resolved = resolveThemeDocument(
			parseTheme(DEFAULT_THEMES.tokyonight as unknown as Record<string, unknown>, "tokyonight"),
			"dark",
		)
		const accent = resolved.hue.accent
		for (const step of [100, 200, 300, 400, 600, 700, 800, 900] as const) {
			expect(accent[step].equals(accent[500])).toBe(false)
		}
	})
})

describe("lucent-orng light mode is readable (fix/theme-legacy)", () => {
	const document = parseTheme(DEFAULT_THEMES["lucent-orng"] as unknown as Record<string, unknown>, "lucent-orng")

	test("surface anchors solidify to the theme's visible surface, opaque", () => {
		for (const mode of modesOf(document)) {
			const resolved = resolveThemeDocument(document, mode)
			// The V1 source surfaces are transparent (#00000000 family); the migration must
			// not anchor the neutral scale on them. (RGBA alpha is a 0..1 float.)
			expect(resolved.background.base.a).toBe(1)
			expect(resolved.background.raised.base.a).toBe(1)
			expect(resolved.background.raised.high.a).toBe(1)
		}
	})

	test("light mode: text on base and raised backgrounds clears WCAG AA (4.5:1)", () => {
		const resolved = resolveThemeDocument(document, "light")
		const text = resolved.text.base
		expect(contrast(text, resolved.background.base)).toBeGreaterThanOrEqual(4.5)
		expect(contrast(text, resolved.background.raised.base)).toBeGreaterThanOrEqual(4.5)
		expect(contrast(text, resolved.background.raised.high)).toBeGreaterThanOrEqual(4.5)
		// and it is a light surface: brighter than the text it carries
		const [r, g, b] = resolved.background.base.toInts()
		expect(r + g + b).toBeGreaterThan(300)
	})

	test("dark mode stays warm-dark and readable (no transparent-black regression)", () => {
		const resolved = resolveThemeDocument(document, "dark")
		expect(contrast(resolved.text.base, resolved.background.base)).toBeGreaterThanOrEqual(4.5)
	})
})
